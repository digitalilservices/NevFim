export function getFurniture3DPlacement(
  model: Furniture3DModel,
): Furniture3DPlacement {
  const categoryPlacement =
    furniture3DCategoryPlacements[model.categoryId] ??
    DEFAULT_3D_PLACEMENT;

  return {
    ...DEFAULT_3D_PLACEMENT,
    ...categoryPlacement,
    ...model.placement,
    position:
      model.placement?.position ??
      categoryPlacement.position ??
      DEFAULT_3D_PLACEMENT.position,
    rotation:
      model.placement?.rotation ??
      categoryPlacement.rotation ??
      DEFAULT_3D_PLACEMENT.rotation,
  };
}

