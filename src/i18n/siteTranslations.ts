export function formatModelCount(language: Language, count: number) {
  if (language === "en") {
    return `${count} ${count === 1 ? "model" : "models"}`;
  }

  if (language === "cs") {
    if (count === 1) return "1 model";
    if (count >= 2 && count <= 4) return `${count} modely`;
    return `${count} modelů`;
  }

  const mod10 = count % 10;
  const mod100 = count % 100;
  if (mod10 === 1 && mod100 !== 11) return `${count} модель`;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) {
    return `${count} модели`;
  }
  return `${count} моделей`;
}
